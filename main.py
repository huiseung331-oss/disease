import streamlit as st
import pandas as pd

# ----------------------------------------------------
# 1. 페이지 기본 설정 (브라우저 탭 제목, 아이콘, 레이아웃)
# ----------------------------------------------------
st.set_page_config(
    page_title="뇌졸중 예측 실습실",
    page_icon="🧠",
    layout="wide"
)

# ----------------------------------------------------
# 2. 데이터 불러오기
#    - @st.cache_data를 사용하면 매번 새로 불러오지 않고
#      한 번 불러온 데이터를 저장해두었다가 재사용해서 앱이 빨라져요.
# ----------------------------------------------------
@st.cache_data
def load_data():
    url = "https://raw.githubusercontent.com/greatsong/modudata/main/data/stroke.csv"
    df = pd.read_csv(url, encoding="utf-8")
    return df

df = load_data()

# ----------------------------------------------------
# 3. 화면 제목
# ----------------------------------------------------
st.title("🧠 뇌졸중 예측 실습실")
st.markdown("뇌졸중(stroke) 데이터를 살펴보고 분석해보는 실습 공간입니다.")
st.divider()

# ----------------------------------------------------
# 4. 큰 숫자 카드 네 개 (st.metric 사용)
# ----------------------------------------------------
전체_인원수 = len(df)
전체_열개수 = df.shape[1]
뇌졸중_인원수 = int(df["stroke"].sum())
뇌졸중_비율 = round(뇌졸중_인원수 / 전체_인원수 * 100, 2)

col1, col2, col3, col4 = st.columns(4)
col1.metric("전체 사람 수", f"{전체_인원수:,} 명")
col2.metric("열 개수", f"{전체_열개수} 개")
col3.metric("뇌졸중 발생자 수 (stroke=1)", f"{뇌졸중_인원수:,} 명")
col4.metric("뇌졸중 비율", f"{뇌졸중_비율} %")

st.divider()

# ----------------------------------------------------
# 5. 열 설명표 만들기
#    - '우리말 뜻'은 비워두고 학생이 직접 채우도록 함
#    - 값의 종류: 숫자형이면 최소~최대, 범주형이면 고유값 목록
#    - 빈 값 개수: 결측치 개수
# ----------------------------------------------------
st.subheader("📋 열(컬럼) 설명표")
st.markdown("아래 표의 **'우리말 뜻'** 칸은 비어 있습니다. 교재를 참고해서 직접 채워보세요!")

컬럼_설명_목록 = []

for 열이름 in df.columns:
    빈값개수 = df[열이름].isnull().sum()

    # 숫자형 열인지 범주형 열인지 구분해서 값의 종류를 다르게 표시
    if pd.api.types.is_numeric_dtype(df[열이름]):
        고유값_개수 = df[열이름].nunique()
        # 고유값이 적으면(예: 0/1 같은 경우) 목록으로, 많으면 범위로 표시
        if 고유값_개수 <= 10:
            값의_종류 = ", ".join(map(str, sorted(df[열이름].dropna().unique())))
        else:
            최소값 = df[열이름].min()
            최대값 = df[열이름].max()
            값의_종류 = f"{최소값} ~ {최대값} (숫자)"
    else:
        고유값_목록 = df[열이름].dropna().unique()
        값의_종류 = ", ".join(map(str, 고유값_목록))

    컬럼_설명_목록.append({
        "열 이름": 열이름,
        "우리말 뜻": "",   # 학생이 직접 채워 넣을 빈 칸
        "값의 종류": 값의_종류,
        "빈 값 개수": 빈값개수
    })

설명표_df = pd.DataFrame(컬럼_설명_목록)

# data_editor를 사용하면 학생이 표 안의 '우리말 뜻' 칸을 직접 클릭해서 입력할 수 있어요.
편집된_설명표 = st.data_editor(
    설명표_df,
    use_container_width=True,
    num_rows="fixed",
    disabled=["열 이름", "값의 종류", "빈 값 개수"]  # 우리말 뜻 칸만 수정 가능
)

st.divider()

# ----------------------------------------------------
# 6. 데이터 처음 다섯 줄 보여주기
# ----------------------------------------------------
st.subheader("🔍 데이터 미리보기 (처음 5줄)")
st.dataframe(df.head(5), use_container_width=True)

st.divider()

# ----------------------------------------------------
# 7. 데이터 출처 적는 자리
# ----------------------------------------------------
st.subheader("📚 데이터 출처")
st.text_area(
    "교재를 참고해서 데이터 출처를 아래에 적어보세요.",
    placeholder="여기에 데이터 출처를 입력하세요...",
    height=100
)
